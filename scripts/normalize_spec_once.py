def insert_section_end(document: str, heading: str, block: str) -> str:
    pos = document.index(heading)
    content_start = pos + len(heading)
    match = re.search(r"\n##\s+", document[content_start:])
    end_pos = content_start + match.start() if match else len(document)
    return (
        document[:end_pos].rstrip()
        + "\n\n"
        + block.rstrip()
        + "\n\n"
        + document[end_pos:].lstrip("\n")
    )


